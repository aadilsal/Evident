"""`evident export --format md`: a commit-stamped architecture report where every row cites code."""

from __future__ import annotations

from collections import defaultdict

from evident import ENGINE_VERSION
from evident.models import Evidence, Graph, Node
from evident.query import GraphIndex, walk

SEVERITY_ORDER = {"error": 0, "warning": 1, "info": 2}
REQUEST_EDGES = frozenset({"handles", "calls"})


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def evidence_link(graph: Graph, ev: Evidence) -> str:
    """`file:line`, linked to the exact commit on GitHub when the repo is hosted there."""
    ref = ev.ref
    repo = graph.repo
    if repo.host != "github.com" or not repo.owner:
        return f"`{ref}`"
    lines = f"L{ev.start_line}" + (f"-L{ev.end_line}" if ev.end_line != ev.start_line else "")
    url = f"https://github.com/{repo.owner}/{repo.name}/blob/{ev.sha}/{ev.file}#{lines}"
    return f"[`{ref}`]({url})"


def _first(graph: Graph, node: Node) -> str:
    return evidence_link(graph, node.evidence[0]) if node.evidence else ""


def route_access(idx: GraphIndex, route_id: str) -> dict[str, set[str]]:
    """Model label -> {read, write} reachable from a route through its handler and calls."""
    out: dict[str, set[str]] = defaultdict(set)
    hops = walk(idx, [route_id], forward=True, depth=12, edge_types=REQUEST_EDGES)
    for hop in hops:
        for e in idx.outgoing[hop.node_id]:
            if e.type in ("reads", "writes") and e.dst.startswith("model:"):
                out[idx.nodes[e.dst].label].add("read" if e.type == "reads" else "write")
    return out


def render_markdown(graph: Graph) -> str:
    idx = GraphIndex(graph)
    repo = graph.repo
    by_type: dict[str, list[Node]] = defaultdict(list)
    for n in graph.nodes:
        by_type[n.type].append(n)
    name = f"{repo.owner}/{repo.name}" if repo.owner else repo.name
    stack = graph.stack or {}
    out = [
        f"# Architecture: {name}",
        "",
        f"> Generated by [Evident](https://github.com/aadilsal/Evident) {ENGINE_VERSION} "
        f"from commit `{repo.sha[:12]}` on {repo.analyzed_at}."
        " Every row cites the code that proves it; regenerate with `evident export --format md`.",
        "",
    ]
    if stack.get("adapters"):
        out.append(f"**Stack:** {', '.join(stack['adapters'])}.")
    if stack.get("message"):
        out.append(f"**Note:** {stack['message']}")
    counts = ", ".join(
        f"{len(by_type[t])} {label if len(by_type[t]) != 1 else label.removesuffix('s')}"
        for t, label in (
            ("route", "routes"),
            ("model", "models"),
            ("service", "external services"),
            ("envVar", "env vars"),
        )
    )
    out += [f"**Summary:** {counts}, {len(graph.findings)} findings.", ""]

    routes = sorted(by_type["route"], key=lambda n: (str(n.attrs.get("path")), n.id))
    if routes:
        out += [
            "## Routes",
            "",
            "| Route | Kind | Handler | Guarded by | Data | Evidence |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for r in routes:
            handler = next(
                (idx.nodes[e.dst].label for e in idx.outgoing[r.id] if e.type == "handles"), ""
            )
            guards = ", ".join(
                sorted(idx.nodes[e.src].label for e in idx.incoming[r.id] if e.type == "guards")
            )
            data = ", ".join(
                f"{m} ({'/'.join(sorted(ops))})"
                for m, ops in sorted(route_access(idx, r.id).items())
            )
            doubt = " *(inferred)*" if r.source == "inferred" else ""
            out.append(
                f"| `{_cell(r.label)}`{doubt} | {r.attrs.get('kind', '')} | {_cell(handler)} | "
                f"{_cell(guards) or '-'} | {_cell(data) or '-'} | {_first(graph, r)} |"
            )
        out.append("")

    models = sorted(by_type["model"], key=lambda n: n.label)
    if models:
        out += [
            "## Data model",
            "",
            "| Model | Table | ORM | Fields | Relations | Evidence |",
            "| --- | --- | --- | --: | --- | --- |",
        ]
        for m in models:
            rels = ", ".join(
                sorted(idx.nodes[e.dst].label for e in idx.outgoing[m.id] if e.type == "relates")
            )
            out.append(
                f"| {m.label} | `{m.attrs.get('tableName', m.label)}` | {m.attrs.get('orm', '')} | "
                f"{len(m.attrs.get('fields', []))} | {rels or '-'} | {_first(graph, m)} |"
            )
        out.append("")

    services = sorted(by_type["service"], key=lambda n: n.label)
    if services:
        out += [
            "## External services",
            "",
            "| Service | Packages | Evidence |",
            "| --- | --- | --- |",
        ]
        for s in services:
            pkgs = ", ".join(f"`{p}`" for p in s.attrs.get("packages", []))
            out.append(f"| {s.label} | {pkgs} | {_first(graph, s)} |")
        out.append("")

    env = sorted(by_type["envVar"], key=lambda n: n.label)
    if env:
        out += [
            "## Environment variables",
            "",
            "| Name | Documented | Read at |",
            "| --- | --- | --- |",
        ]
        for v in env:
            documented = "yes" if v.attrs.get("documented") else "**no**"
            out.append(f"| `{v.label}` | {documented} | {_first(graph, v)} |")
        out += ["", "Names only: values are never read.", ""]

    containers = sorted(by_type["container"], key=lambda n: n.label)
    if containers:
        out += [
            "## Containers",
            "",
            "| Service | Image / build | Ports | Evidence |",
            "| --- | --- | --- | --- |",
        ]
        for c in containers:
            source = c.attrs.get("image") or c.attrs.get("build") or ""
            ports = ", ".join(c.attrs.get("ports", []))
            out.append(f"| {c.label} | `{source}` | {ports or '-'} | {_first(graph, c)} |")
        out.append("")

    findings = sorted(graph.findings, key=lambda f: (SEVERITY_ORDER[f.severity], f.id))
    out += ["## Health findings", ""]
    if not findings:
        out += ["No findings.", ""]
    else:
        out += ["| Severity | Finding | Evidence |", "| --- | --- | --- |"]
        for f in findings:
            ev = evidence_link(graph, f.evidence[0]) if f.evidence else ""
            out.append(f"| {f.severity} | {_cell(f.message)} | {ev} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"
