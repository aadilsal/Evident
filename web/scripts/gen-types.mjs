// Generates src/lib/schema.ts from schema/graph.schema.json, so web types can't drift from the contract.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "..", "schema", "graph.schema.json");
const outPath = join(root, "src", "lib", "schema.ts");

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ts = await compile(schema, "Graph", {
  bannerComment:
    "/* Generated by web/scripts/gen-types.mjs from schema/graph.schema.json. Do not edit by hand. */",
  additionalProperties: false,
  style: { singleQuote: false, semi: true, printWidth: 100 },
  cwd: dirname(schemaPath),
});
// Per-type attrs live in if/then branches the compiler can't see; emit each one explicitly.
const attrDefs = Object.keys(schema.$defs).filter((k) => k.endsWith("Attrs"));
const attrTypes = [];
for (const key of attrDefs) {
  const title = key[0].toUpperCase() + key.slice(1);
  const part = await compile({ ...schema.$defs[key], title, $defs: schema.$defs }, title, {
    bannerComment: "",
    additionalProperties: false,
    declareExternallyReferenced: false,
    style: { singleQuote: false, semi: true, printWidth: 100 },
  });
  attrTypes.push(part.replace(/^export type (RepoPath|NodeId|Sha) = string;\n/gm, ""));
}
const major = schema.properties.schemaVersion.pattern.match(/^\^(\d+)/)?.[1] ?? "1";
const versioned = `${ts}\n${attrTypes.join("\n")}\nexport const SUPPORTED_SCHEMA_MAJOR = ${major};\n`;

if (process.argv.includes("--check")) {
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== versioned) {
    console.error("src/lib/schema.ts is stale: run `npm run gen:types`.");
    process.exit(1);
  }
  console.log("schema.ts is up to date");
} else {
  writeFileSync(outPath, versioned);
  console.log(`wrote ${outPath}`);
}
