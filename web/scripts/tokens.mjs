// Generates src/styles/tokens.css from DESIGN.md front matter. `--check` fails if the file is stale.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const designPath = join(root, "..", "DESIGN.md");
const outPath = join(root, "src", "styles", "tokens.css");

const md = readFileSync(designPath, "utf8").replace(/\r\n/g, "\n");
const front = md.match(/^---\n([\s\S]*?)\n---/);
if (!front) throw new Error("DESIGN.md has no front matter");
const design = parse(front[1]);

function hexToHsl(hex) {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => v / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  return [h * 60, s, l];
}

function hsl([h, s, l]) {
  return `hsl(${h.toFixed(1)} ${(s * 100).toFixed(1)}% ${(l * 100).toFixed(1)}%)`;
}

function rgba(hex, alpha) {
  const n = parseInt(hex.slice(1), 16);
  return `rgb(${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255} / ${alpha})`;
}

const c = design.colors;
const lines = [];
const out = (s = "") => lines.push(s);

out("/* Generated by web/scripts/tokens.mjs from DESIGN.md. Do not edit by hand. */");
out();
out(":root {");
for (const [name, value] of Object.entries(c)) out(`  --ev-${name}: ${value};`);
out("}");
out();
// Light mode is the binder page: paper and ink; layer colours darken ~15% lightness (DESIGN.md Colors).
out('[data-theme="light"] {');
out(`  --ev-surface: ${c.paper};`);
out(`  --ev-surface-raised: ${c.paper};`);
out(`  --ev-surface-sunken: ${hsl(((h) => [h[0], h[1], h[2] - 0.04])(hexToHsl(c.paper)))};`);
out(`  --ev-on-surface: ${c.ink};`);
out(`  --ev-on-surface-muted: ${hsl(((h) => [h[0], h[1], 0.38])(hexToHsl(c.ink)))};`);
out(`  --ev-outline: ${hsl(((h) => [h[0], h[1], h[2] - 0.12])(hexToHsl(c.paper)))};`);
out(`  --ev-outline-strong: ${hsl(((h) => [h[0], h[1], h[2] - 0.3])(hexToHsl(c.paper)))};`);
out(`  --ev-highlight: ${rgba(c.primary, 0.18)};`);
for (const [name, value] of Object.entries(c)) {
  if (name.startsWith("layer-") || name === "error" || name === "warning") {
    const [h, s, l] = hexToHsl(value);
    out(`  --ev-${name}: ${hsl([h, s, Math.max(0, l - 0.15)])};`);
  }
}
out("}");
out();
out("@theme inline {");
for (const name of Object.keys(c)) out(`  --color-${name}: var(--ev-${name});`);
for (const [name, value] of Object.entries(design.rounded)) out(`  --radius-${name}: ${value};`);
for (const [name, value] of Object.entries(design.spacing)) out(`  --spacing-${name}: ${value};`);
const families = {
  "IBM Plex Sans": "var(--font-plex-sans)",
  "IBM Plex Sans Condensed": "var(--font-plex-condensed)",
  "IBM Plex Mono": "var(--font-plex-mono)",
};
out("  --font-sans: var(--font-plex-sans), ui-sans-serif, system-ui, sans-serif;");
out("  --font-condensed: var(--font-plex-condensed), var(--font-plex-sans), sans-serif;");
out("  --font-mono: var(--font-plex-mono), ui-monospace, monospace;");
for (const [name, t] of Object.entries(design.typography)) {
  out(`  --text-${name}: ${t.fontSize};`);
  out(`  --text-${name}--line-height: ${t.lineHeight};`);
  if (t.letterSpacing) out(`  --text-${name}--letter-spacing: ${t.letterSpacing};`);
  out(`  --text-${name}--font-weight: ${t.fontWeight};`);
}
out(`  --ease-standard: ${design.motion["ease-standard"]};`);
out(`  --ease-draw: ${design.motion["ease-draw"]};`);
out("}");
out();
out(":root {");
for (const [name, t] of Object.entries(design.typography)) {
  out(`  --ev-font-${name}: ${families[t.fontFamily] ?? "inherit"};`);
}
for (const [name, value] of Object.entries(design.motion)) {
  if (!name.startsWith("ease")) out(`  --ev-motion-${name}: ${value};`);
}
out("}");
out();

const css = lines.join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== css) {
    console.error("src/styles/tokens.css is stale: run `npm run tokens`.");
    process.exit(1);
  }
  console.log("tokens.css is up to date");
} else {
  writeFileSync(outPath, css);
  console.log(`wrote ${outPath}`);
}
